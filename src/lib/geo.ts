const BY_SLUG = new Map(STATES.map((s) => [s.slug, s]));
const BY_CODE = new Map(STATES.map((s) => [s.code, s]));

export function stateBySlug(slug: string) {
  return BY_SLUG.get(slug);
}

export function stateByCode(code: string) {
  return BY_CODE.get(code);
}

// URL-safe slug: lowercase, strip diacritics (Cañon City -> canon-city,
// Kapaʻa -> kapaa), collapse non-alphanumerics to single hyphens.
export function slugify(input: string): string {
  return input
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "") // strip combining diacritics (ñ -> n)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

// Listing slugs append the numeric id (store-name-26925) since ~200 rows
// share name+city+state and a bare name slug wouldn't be unique.
export function storeSlug(name: string, id: number): string {
  return `${slugify(name)}-${id}`;
}

// Pull the id back out of a listing URL segment; returns null if it doesn't
// look like one of ours so the route can 404 cleanly.
export function parseStoreSlug(segment: string): number | null {
  const match = segment.match(/-(\d+)$/);
  if (!match) return null;
  return Number(match[1]);
}
